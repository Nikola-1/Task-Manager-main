const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const assert = require('node:assert/strict');
const moduleContext = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/features/habits/data/habits.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2017 } }).outputText, moduleContext);
const { streakSummary } = moduleContext.exports;
const habit = { id: 'a', name: 'Read', period: 'Morning', icon: 'read', createdOn: '2025-12-01', completedDates: ['2025-12-30', '2025-12-31', '2026-01-01', '2026-01-01', '2026-01-04', '2026-01-06', '2025-11-30'] };
let result = streakSummary(habit, new Date(2026, 0, 5, 12));
assert.equal(result.longest, 3, 'Consecutive dates cross the year boundary');
assert.equal(result.current, 1, 'Yesterday streak remains active before today is completed');
assert.equal(result.completed.length, 4, 'Ignore duplicates, future and precreation dates');
assert.equal(result.ranges.length, 2, 'Missing days split ranges');
assert.equal(result.ranges[0].start, '2025-12-30');
assert.equal(result.ranges[0].end, '2026-01-01');
assert.equal(streakSummary(habit, new Date(2026, 0, 3, 12)).current, 0, 'A missed day breaks the current streak');
result = streakSummary({ ...habit, createdOn: '2024-02-01', completedDates: ['2024-02-28', '2024-02-29', '2024-03-01'] }, new Date(2024, 2, 1, 12));
assert.equal(result.current, 3); assert.equal(result.longest, 3, 'Leap day belongs to a continuous streak');
assert.equal(streakSummary({ ...habit, completedDates: [] }, new Date()).longest, 0);
console.log('Streak checks passed: year and month boundaries, leap day, gaps, today, empty history and duplicate exclusion.');
